import Foundation
import UIKit
import os

/// Launch-argument runner, result files and process metrics shared by every spike.
@MainActor
final class Harness {
    static let shared = Harness()
    private(set) weak var controller: SpikeViewController?
    var stage: UIView { controller!.stage }

    func attach(_ controller: SpikeViewController) { self.controller = controller }

    // MARK: Arguments

    let args = ProcessInfo.processInfo.arguments

    func value(_ flag: String) -> String? {
        guard let i = args.firstIndex(of: flag), args.indices.contains(i + 1) else { return nil }
        return args[i + 1]
    }

    func double(_ flag: String, default d: Double) -> Double { value(flag).flatMap(Double.init) ?? d }
    func int(_ flag: String, default d: Int) -> Int { value(flag).flatMap(Int.init) ?? d }
    var exitWhenDone: Bool { args.contains("--exit") }

    func startFromLaunchArguments() {
        guard let spike = value("--spike") else {
            log("CCSpikes ready. Launch with --spike <a…g> [--variant v] [--exit].")
            log(Metrics.deviceSummary().map { "\($0.key)=\($0.value)" }.sorted().joined(separator: " "))
            return
        }
        let variant = value("--variant") ?? "default"
        // Scripted runs must not let the phone auto-lock: a locked device
        // refuses the next launch.
        UIApplication.shared.isIdleTimerDisabled = true
        let cooldown = double("--cooldown", default: 0)
        Task { @MainActor in
            // Thermal cool-down happens HERE, in the foreground with the idle
            // timer off, so the device never sits on the Home Screen long
            // enough to lock between launches.
            if cooldown > 0 {
                log("cooling down \(Int(cooldown)) s (thermal \(Metrics.thermal))")
                try? await Task.sleep(nanoseconds: UInt64(cooldown * 1e9))
            }
            // Let the window settle so stage geometry and display link timing are real.
            try? await Task.sleep(nanoseconds: 600_000_000)
            await run(spike: spike, variant: variant)
        }
    }

    func run(spike: String, variant: String) async {
        log("SPIKE-START \(spike)/\(variant)")
        let sampler = MemorySampler()
        sampler.start()
        let started = CACurrentMediaTime()
        var result: [String: Any]
        do {
            switch spike {
            case "a": result = try await SpikeA.run(variant: variant)
            case "b": result = try await SpikeB.run(variant: variant)
            case "c": result = try await SpikeC.run(variant: variant)
            case "d": result = try await SpikeD.run(variant: variant)
            case "e": result = try await SpikeE.run(variant: variant)
            case "f": result = try await SpikeF.run(variant: variant)
            case "g": result = try await SpikeG.run(variant: variant)
            default: result = ["error": "unknown spike \(spike)"]
            }
        } catch {
            result = ["error": "\(error)"]
        }
        let mem = sampler.stop()
        result["spike"] = spike
        result["variant"] = variant
        result["wallSeconds"] = CACurrentMediaTime() - started
        result["memory"] = mem
        result["device"] = Metrics.deviceSummary()
        write(result, name: "\(spike)-\(variant)")
        if exitWhenDone {
            try? await Task.sleep(nanoseconds: 300_000_000)
            exit(0)
        }
    }

    // MARK: Output

    nonisolated func log(_ line: String) {
        print("SPIKE-LOG \(line)")
        fflush(stdout)
        Task { @MainActor in self.controller?.append(line) }
    }

    func write(_ result: [String: Any], name: String) {
        let json = (try? JSONSerialization.data(withJSONObject: Metrics.sanitize(result), options: [.sortedKeys]))
            ?? Data("{}".utf8)
        let pretty = (try? JSONSerialization.data(withJSONObject: Metrics.sanitize(result), options: [.sortedKeys, .prettyPrinted]))
            ?? json
        let dir = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("results", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try? pretty.write(to: dir.appendingPathComponent("\(name).json"))
        print("SPIKE-RESULT " + (String(data: json, encoding: .utf8) ?? "{}"))
        fflush(stdout)
        controller?.append("SPIKE-DONE \(name) → Documents/results/\(name).json")
    }

    /// A bundled media file (generated by mac/make-media.sh into Spikes/Media).
    func media(_ name: String) throws -> URL {
        if let url = Bundle.main.url(forResource: name, withExtension: nil) { return url }
        let docs = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0]
            .appendingPathComponent(name)
        if FileManager.default.fileExists(atPath: docs.path) { return docs }
        throw SpikeError("missing media \(name) — run apps/ios-spikes/mac/make-media.sh and rebuild")
    }
}

struct SpikeError: Error, CustomStringConvertible {
    let description: String
    init(_ d: String) { description = d }
}

// MARK: - Metrics

enum Metrics {
    /// (current phys_footprint, process-lifetime peak) in bytes — the number
    /// jetsam judges the app by.
    static func footprint() -> (current: UInt64, peak: UInt64) {
        var info = task_vm_info_data_t()
        var count = mach_msg_type_number_t(MemoryLayout<task_vm_info_data_t>.stride / MemoryLayout<integer_t>.stride)
        let kr = withUnsafeMutablePointer(to: &info) {
            $0.withMemoryRebound(to: integer_t.self, capacity: Int(count)) {
                task_info(mach_task_self_, task_flavor_t(TASK_VM_INFO), $0, &count)
            }
        }
        guard kr == KERN_SUCCESS else { return (0, 0) }
        return (info.phys_footprint, UInt64(max(0, info.ledger_phys_footprint_peak)))
    }

    static func availableMemory() -> UInt64 { UInt64(os_proc_available_memory()) }

    static var machine: String {
        var u = utsname()
        uname(&u)
        return withUnsafeBytes(of: &u.machine) { raw in
            String(decoding: raw.prefix(while: { $0 != 0 }), as: UTF8.self)
        }
    }

    static var thermal: String {
        switch ProcessInfo.processInfo.thermalState {
        case .nominal: return "nominal"
        case .fair: return "fair"
        case .serious: return "serious"
        case .critical: return "critical"
        @unknown default: return "unknown"
        }
    }

    static func mb(_ bytes: UInt64) -> Double { (Double(bytes) / 1_048_576 * 10).rounded() / 10 }

    @MainActor static func deviceSummary() -> [String: Any] {
        let screen = UIScreen.main
        #if targetEnvironment(simulator)
        let simulated = true
        #else
        let simulated = false
        #endif
        return [
            "machine": machine,
            "model": UIDevice.current.model,
            "system": "\(UIDevice.current.systemName) \(UIDevice.current.systemVersion)",
            "simulator": simulated,
            "physicalMemoryMB": mb(ProcessInfo.processInfo.physicalMemory),
            "cores": ProcessInfo.processInfo.activeProcessorCount,
            "maxFPS": screen.maximumFramesPerSecond,
            "screenPoints": "\(Int(screen.bounds.width))x\(Int(screen.bounds.height))@\(screen.scale)",
            "thermal": thermal,
            "lowPower": ProcessInfo.processInfo.isLowPowerModeEnabled,
        ]
    }

    /// JSONSerialization rejects NaN/inf.
    static func sanitize(_ v: Any) -> Any {
        switch v {
        case let d as Double: return d.isFinite ? (d * 1e6).rounded() / 1e6 : "\(d)"
        case let f as Float: return sanitize(Double(f))
        case let a as [Any]: return a.map(sanitize)
        case let m as [String: Any]: return m.mapValues(sanitize)
        default: return v
        }
    }

    /// Summary statistics of a sample (ms or any unit).
    static func stats(_ xs: [Double]) -> [String: Any] {
        guard !xs.isEmpty else { return ["n": 0] }
        let s = xs.sorted()
        func q(_ p: Double) -> Double { s[min(s.count - 1, Int((Double(s.count - 1) * p).rounded()))] }
        let mean = xs.reduce(0, +) / Double(xs.count)
        let sd = (xs.map { ($0 - mean) * ($0 - mean) }.reduce(0, +) / Double(xs.count)).squareRoot()
        return ["n": xs.count, "mean": mean, "sd": sd, "p50": q(0.5), "p95": q(0.95), "p99": q(0.99),
                "min": s.first!, "max": s.last!]
    }
}

/// Samples phys_footprint and os_proc_available_memory every 20 ms.
final class MemorySampler: @unchecked Sendable {
    private let queue = DispatchQueue(label: "spike.memory")
    private var timer: DispatchSourceTimer?
    private var peak: UInt64 = 0
    private var minAvailable: UInt64 = .max
    private var startFootprint: UInt64 = 0

    func start() {
        startFootprint = Metrics.footprint().current
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now(), repeating: .milliseconds(20))
        t.setEventHandler { [weak self] in
            guard let self else { return }
            let f = Metrics.footprint().current
            if f > self.peak { self.peak = f }
            let a = Metrics.availableMemory()
            if a > 0, a < self.minAvailable { self.minAvailable = a }
        }
        t.resume()
        timer = t
    }

    func stop() -> [String: Any] {
        timer?.cancel()
        let f = Metrics.footprint()
        return queue.sync {
            [
                "startFootprintMB": Metrics.mb(startFootprint),
                "sampledPeakFootprintMB": Metrics.mb(peak),
                "processPeakFootprintMB": Metrics.mb(f.peak),
                "endFootprintMB": Metrics.mb(f.current),
                "minAvailableMB": minAvailable == .max ? -1 : Metrics.mb(minAvailable),
                "thermalAtEnd": Metrics.thermal,
            ]
        }
    }
}
