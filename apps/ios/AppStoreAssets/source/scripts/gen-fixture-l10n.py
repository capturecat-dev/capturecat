#!/usr/bin/env python3
"""source/fixture-l10n.json -> App/Fixtures/StoreFixtureL10n.swift (DEBUG fixture only).

    python3 gen-fixture-l10n.py <path to apps/ios in the store worktree>
"""
import json, sys
from pathlib import Path

src = Path(__file__).resolve().parents[1] / "fixture-l10n.json"
data = {k: v for k, v in json.loads(src.read_text()).items() if not k.startswith("_")}
def lit(s): return json.dumps(s, ensure_ascii=False)
rows = []
for lang, table in data.items():
    rows.append(f"        {lit(lang)}: [")
    rows += [f"            {lit(k)}: {lit(v)}," for k, v in table.items()]
    rows.append("        ],")
swift = f'''#if DEBUG
import Foundation

// Generated by AppStoreAssets/source/scripts/gen-fixture-l10n.py from
// AppStoreAssets/source/fixture-l10n.json — edit the JSON, not this file.
//
/// The store fixture's own visible content (project names, comments, the
/// synthetic recorded web app, the demo captions) in the app's language, for
/// App Store creative: `-uiStoreLocalizedContent` turns it on; otherwise the
/// fixture stays English (the l10n gate compares fixture runs to English).
enum StoreL10n {{
    static let table: [String: [String: String]] = [
{chr(10).join(rows)}
    ]

    static let language: String = {{
        guard FixtureWorld.has("-uiStoreLocalizedContent") else {{ return "en" }}
        let preferred = FixtureWorld.value("-uiStoreLang") ?? Bundle.main.preferredLocalizations.first ?? "en"
        if table[preferred] != nil {{ return preferred }}
        let base = String(preferred.split(separator: "-").first ?? "en")
        return table[base] != nil ? base : "en"
    }}()

    static func t(_ key: String) -> String {{
        table[language]?[key] ?? table["en"]?[key] ?? key
    }}
}}
#endif
'''
out = Path(sys.argv[1]) / "App" / "Fixtures" / "StoreFixtureL10n.swift"
out.write_text(swift)
print(f"wrote {out} ({len(data)} languages)")
