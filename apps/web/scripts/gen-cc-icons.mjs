#!/usr/bin/env node
/**
 * Generates src/editor/ui/kit/ccIcons.generated.ts from apps/macos/IconKit/icons.json —
 * CaptureCat's own icon kit (the Mac's Views/Shared/DesignKit/CCIconSet.swift
 * draws the same set). The JSON is checked in next to this script so the build
 * never depends on where the kit was drawn; re-export it from the kit's source
 * and re-run:
 *
 *   node scripts/gen-cc-icons.mjs [path/to/icons.json]
 *
 * Shape of the JSON: `icons` (kit name → SVG inner markup on a 24×24 grid,
 * every element stroked 1.75 with round caps/joins; `fill="currentColor"`
 * adds a nonzero fill), `aliases` (SF Symbol name → kit name; the web editor
 * asks for icons by their Swift SF names), `kitOnlyAliases` (SF-style names
 * the kit adds that SF itself does not have).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
// The ONE kit source both apps build from (the Mac regenerates CCIconSet.swift
// from the same file with apps/macos/IconKit/gen-iconset.py).
const src = process.argv[2] ?? path.join(here, "../../macos/IconKit/icons.json");
const out = path.join(here, "../src/editor/ui/kit/ccIcons.generated.ts");

const json = JSON.parse(fs.readFileSync(src, "utf8"));
const { icons, aliases, style } = json;
if (!icons || !aliases) throw new Error(`${src}: expected { icons, aliases }`);

const ALLOWED_TAGS = new Set(["path", "rect", "circle", "line"]);
const ALLOWED_ATTRS = new Set(["d", "fill", "x", "y", "width", "height", "rx", "ry", "cx", "cy", "r", "x1", "y1", "x2", "y2", "stroke"]);
for (const [name, markup] of Object.entries(icons)) {
  for (const m of markup.matchAll(/<(\w+)([^>]*)\/?>/g)) {
    if (!ALLOWED_TAGS.has(m[1])) throw new Error(`${name}: unexpected <${m[1]}>`);
    for (const a of m[2].matchAll(/([a-zA-Z-]+)=/g)) {
      if (!ALLOWED_ATTRS.has(a[1])) throw new Error(`${name}: unexpected attribute ${a[1]}`);
    }
  }
}
for (const [sf, kit] of Object.entries(aliases)) {
  if (!icons[kit]) throw new Error(`alias ${sf} → ${kit}: no such kit icon`);
}

const sortObj = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const lines = [
  "/* eslint-disable */",
  "// GENERATED by scripts/gen-cc-icons.mjs from apps/macos/IconKit/icons.json — do not edit.",
  "// CaptureCat's icon kit (CCIconSet on the Mac): 24×24 grid, every element",
  `// stroked ${style?.stroke ?? 1.75} with round caps/joins; fill="currentColor" adds a nonzero fill.`,
  "",
  `export const CC_ICON_STROKE = ${JSON.stringify(style?.stroke ?? 1.75)};`,
  "",
  "/** Kit name → SVG inner markup (24-unit grid). */",
  `export const CC_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(sortObj(icons), null, 2)};`,
  "",
  "/** SF Symbol name (as the Swift sources spell it) → kit name. */",
  `export const CC_ICON_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(sortObj(aliases), null, 2)};`,
  "",
];
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), out)}: ${Object.keys(icons).length} icons, ${Object.keys(aliases).length} aliases`);
